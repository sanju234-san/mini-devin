"""Endpoints for the Implementation Plan, Diff, Test Log, and PR artifact trail.

This module exposes the artifacts generated by agents during an execution run:
- GET /runs/{run_id}/artifacts: List metadata for all artifacts of a run.
- GET /runs/{run_id}/artifacts/{artifact_id}: Retrieve text content for
  text-based artifacts (implementation plan, diff, test log, walkthrough).

Security & Scope Constraints:
- No private reasoning: Internal chain-of-thought and scratchpads are never
  exposed in artifact responses.
- Binary artifact guard: Screenshots and recordings are not downloadable via
  this endpoint yet and return HTTP 501 Not Implemented.
- No direct file paths: Artifacts are purely managed in memory/database without
  accepting or exposing arbitrary filesystem paths.
"""

from __future__ import annotations

from uuid import UUID

from fastapi import APIRouter, Depends, HTTPException, status

from app.api.deps import get_run_store
from app.api.run_store import RunStore
from app.models.artifact import ArtifactContent, ArtifactOut, ArtifactType

router = APIRouter(prefix="/runs/{run_id}/artifacts", tags=["artifacts"])

# Binary artifacts whose direct text download is not supported in this task
BINARY_ARTIFACT_TYPES = frozenset({
    ArtifactType.screenshot,
    ArtifactType.recording,
})


@router.get(
    "",
    response_model=list[ArtifactOut],
    summary="List all artifacts for a run",
)
async def list_artifacts(
    run_id: UUID,
    store: RunStore = Depends(get_run_store),
) -> list[ArtifactOut]:
    """Return all artifact metadata items associated with the specified run.

    Returns HTTP 404 if the run does not exist.
    """
    artifacts = await store.list_artifacts(run_id)
    if artifacts is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Run not found",
        )
    return artifacts


@router.get(
    "/{artifact_id}",
    response_model=ArtifactContent,
    summary="Get text content of an artifact",
)
async def get_artifact(
    run_id: UUID,
    artifact_id: UUID,
    store: RunStore = Depends(get_run_store),
) -> ArtifactContent:
    """Retrieve the text content and metadata of a specific artifact.

    Returns HTTP 404 if the run or artifact is not found.
    Returns HTTP 501 if attempting to fetch binary content (screenshot/recording).
    """
    # Verify the run exists first
    run = await store.get_run(run_id)
    if run is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Run not found",
        )

    result = await store.get_artifact(run_id, artifact_id)
    if result is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Artifact not found",
        )

    artifact_out, content_str = result

    # Binary artifacts require specialized object storage streaming (later task)
    if artifact_out.type in BINARY_ARTIFACT_TYPES:
        raise HTTPException(
            status_code=status.HTTP_501_NOT_IMPLEMENTED,
            detail="Binary artifact download not implemented yet",
        )

    return ArtifactContent(
        artifact=artifact_out,
        content=content_str,
    )
