"""Pydantic v2 schemas for agent-generated artifacts.

This module defines the models for artifacts produced during a run:
implementation plans, code diffs, test logs, screenshots, recordings,
and walkthroughs.

IMPORTANT TRANSPARENCY & SECURITY NOTE:
Private reasoning, scratchpads, and chain-of-thought traces are strictly
excluded from all artifact schemas so internal model deliberations are
never exposed to external callers or UI clients.
"""

from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from uuid import UUID

from pydantic import BaseModel, Field


class ArtifactType(str, Enum):
    """Classification of artifacts produced by agents during a run.

    Values:
        implementation_plan: Natural-language proposed fix and step-by-step plan.
        code_diff: Unified Git diff generated by the coding agent.
        test_log: Output logs from sandbox test executions.
        screenshot: Visual screenshot captured during browser/UI validation.
        recording: Video recording of sandbox verification.
        walkthrough: User-facing summary explaining the completed fix.
    """

    implementation_plan = "implementation_plan"
    code_diff = "code_diff"
    test_log = "test_log"
    screenshot = "screenshot"
    recording = "recording"
    walkthrough = "walkthrough"


class ArtifactOut(BaseModel):
    """Metadata describing a generated artifact.

    Note: There are NO private reasoning or internal chain-of-thought fields
    on this model. Only external, user-facing artifact metadata is exposed.
    """

    id: UUID = Field(..., description="Unique artifact identifier (UUIDv4)")
    run_id: UUID = Field(..., description="ID of the run that generated this artifact")
    type: ArtifactType = Field(..., description="Type of artifact")
    name: str = Field(..., description="Human-readable filename or title")
    content_type: str = Field(
        ...,
        description="MIME content type (e.g. text/plain, text/markdown, image/png)",
    )
    size_bytes: int = Field(..., ge=0, description="Size of artifact content in bytes")
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc),
        description="Timestamp when artifact was recorded (UTC)",
    )
    agent: str | None = Field(
        default=None,
        description="Identifier of the agent that produced this artifact (e.g. coder, planner)",
    )
    model_used: str | None = Field(
        default=None,
        description="LLM model name used to generate this artifact, if applicable",
    )


class ArtifactContent(BaseModel):
    """Artifact metadata combined with its raw text content."""

    artifact: ArtifactOut = Field(..., description="Artifact metadata")
    content: str = Field(..., description="Raw text content of the artifact")
